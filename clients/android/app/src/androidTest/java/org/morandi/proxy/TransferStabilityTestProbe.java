package org.morandi.proxy;

import android.net.Network;
import android.os.SystemClock;
import android.util.Log;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.Proxy;
import java.net.URL;
import java.util.Locale;
import java.util.StringJoiner;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicLong;

import javax.net.ssl.HttpsURLConnection;

/** Repeats bounded public speed-test requests while STUN measures the same VPN. */
final class TransferStabilityTestProbe implements AutoCloseable {
    private static final int BYTES = 2 * 1024 * 1024;
    private static final int MIN_TRANSFERS = 3;
    private static final int MAX_TRANSFERS = 32;
    private static final int IO_TIMEOUT_MS = 5000;
    private static final int TIME_BUDGET_MS = 30_000;

    private final boolean upload;
    private final Network vpn;
    private final Thread worker;
    private final long[] durations = new long[MAX_TRANSFERS];
    private final AtomicLong bytes = new AtomicLong();
    private final CountDownLatch began = new CountDownLatch(1);
    private volatile HttpsURLConnection current;
    private volatile boolean finish;
    private volatile boolean cancelled;
    private volatile long ended;
    private volatile Throwable failure;
    private int completed;

    TransferStabilityTestProbe(Network vpn, boolean upload) {
        this.vpn = vpn;
        this.upload = upload;
        worker = new Thread(this::run, "Android acceptance transfer");
        worker.setDaemon(true);
    }

    void start() throws Exception {
        worker.start();
        if (!began.await(16, TimeUnit.SECONDS)) {
            throw new IOException("ANDROID_LOAD_DID_NOT_START_" + direction());
        }
        checkFailure();
    }

    long bodyBytes() {
        return bytes.get();
    }

    private String direction() {
        return upload ? "UPLOAD" : "DOWNLOAD";
    }

    void finish(long lastProbeEnded, int probesWithBodyProgress) throws IOException, InterruptedException {
        finish = true;
        worker.join(TIME_BUDGET_MS);
        checkFailure();
        if (worker.isAlive() || completed < MIN_TRANSFERS || ended < lastProbeEnded || probesWithBodyProgress < 1) {
            throw new IOException("ANDROID_LOAD_INSUFFICIENT_" + direction()
                    + "_COMPLETED=" + completed + "_PROBES_WITH_BODY_PROGRESS=" + probesWithBodyProgress);
        }
        StringJoiner trials = new StringJoiner(",");
        for (int i = 0; i < completed; i++) {
            trials.add(String.format(Locale.ROOT, "%.2f", BYTES * 8_000.0 / durations[i]));
        }
        Log.i("ProxySpeedAcceptance", "ANDROID_PERF_LOAD_" + direction() + "_RATES_MBPS=" + trials
                + ";N=" + completed + ";BYTES_PER_TRANSFER=" + BYTES
                + ";RTT_SAMPLES=12;PROBES_WITH_BODY_PROGRESS=" + probesWithBodyProgress);
    }

    private void run() {
        long deadline = SystemClock.elapsedRealtime() + TIME_BUDGET_MS;
        byte[] buffer = new byte[32 * 1024];
        // The payload contains only generated bytes and is never read from disk.
        if (upload) new java.security.SecureRandom().nextBytes(buffer);
        try {
            while (!cancelled && completed < MAX_TRANSFERS && (completed < MIN_TRANSFERS || !finish)
                    && SystemClock.elapsedRealtime() < deadline) {
                long start = SystemClock.elapsedRealtimeNanos();
                transfer(buffer, deadline);
                durations[completed++] = SystemClock.elapsedRealtimeNanos() - start;
            }
        } catch (Exception error) {
            failure = error;
        } finally {
            ended = SystemClock.elapsedRealtimeNanos();
            began.countDown();
        }
    }

    private void transfer(byte[] buffer, long deadline) throws IOException {
        String url = "https://speed.cloudflare.com/" + (upload ? "__up" : "__down?bytes=" + BYTES);
        HttpsURLConnection connection = (HttpsURLConnection) vpn.openConnection(new URL(url), Proxy.NO_PROXY);
        current = connection;
        try {
            connection.setConnectTimeout(IO_TIMEOUT_MS);
            connection.setReadTimeout(IO_TIMEOUT_MS);
            connection.setInstanceFollowRedirects(false);
            connection.setUseCaches(false);
            connection.setRequestProperty("Accept-Encoding", "identity");
            if (upload) {
                connection.setRequestMethod("POST");
                connection.setDoOutput(true);
                connection.setFixedLengthStreamingMode(BYTES);
                connection.setRequestProperty("Content-Type", "application/octet-stream");
                try (OutputStream out = connection.getOutputStream()) {
                    for (int sent = 0; sent < BYTES; sent += buffer.length) {
                        out.write(buffer);
                        progressed(buffer.length, deadline);
                    }
                }
            }
            int status = connection.getResponseCode();
            if (status < 200 || status >= 300) {
                throw new IOException("ANDROID_LOAD_HTTP_" + direction() + "=" + status);
            }
            if (!upload) {
                int count = 0;
                try (InputStream in = connection.getInputStream()) {
                    int n;
                    while ((n = in.read(buffer)) != -1) {
                        count += n;
                        if (count > BYTES) throw new IOException("ANDROID_LOAD_OVERSIZED");
                        progressed(n, deadline);
                    }
                }
                if (count != BYTES) throw new IOException("ANDROID_LOAD_TRUNCATED");
            }
        } finally {
            connection.disconnect();
            current = null;
        }
    }

    private void progressed(int count, long deadline) throws IOException {
        if (cancelled || SystemClock.elapsedRealtime() >= deadline) throw new IOException("ANDROID_LOAD_DEADLINE");
        bytes.addAndGet(count);
        began.countDown();
    }

    private void checkFailure() throws IOException {
        if (failure != null) throw new IOException("ANDROID_LOAD_FAILED_" + direction(), failure);
    }

    @Override public void close() {
        cancelled = true;
        HttpsURLConnection connection = current;
        if (connection != null) connection.disconnect();
        worker.interrupt();
    }
}
